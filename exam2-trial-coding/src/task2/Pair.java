package task2;

public class Pair {
    String name;
    int collectedApples;

    public String getName() {
        return name;
    }

    public int getCollectedApples() {
        return collectedApples;
    }

    public Pair(String name, int collectedApples) {
        this.name = name;
        this.collectedApples = collectedApples;
    }
}
